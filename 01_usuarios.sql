SELECT USERNAME, ACCOUNT_STATUS
FROM DBA_USERS
WHERE USERNAME IN (
    'LUBRICAR',
    'LUBRICAR_OPERADOR',
    'LUBRICAR_CONSULTA'
)
ORDER BY USERNAME;


SELECT ROLE
FROM DBA_ROLES
WHERE ROLE IN (
    'LUBRICAR',
    'LUBRICAR_OPERADOR',
    'LUBRICAR_CONSULTA'
);




SELECT GRANTEE, PRIVILEGE
FROM DBA_SYS_PRIVS
WHERE GRANTEE IN (
    'LUBRICAR',
    'LUBRICAR_OPERADOR',
    'LUBRICAR_CONSULTA'
)
AND PRIVILEGE IN (
    'CREATE SESSION',
    'CREATE TABLE'
)
ORDER BY GRANTEE, PRIVILEGE;

