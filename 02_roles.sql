-- CONEXION: FIDEADMIN (ADMIN)
-- 1 Crear los roles

CREATE ROLE ROL_LUBRICAR_OPERADOR;

CREATE ROLE ROL_LUBRICAR_CONSULTA;

-- 2 Asignar cada rol a su usuario

GRANT ROL_LUBRICAR_OPERADOR
TO LUBRICAR_OPERADOR;

GRANT ROL_LUBRICAR_CONSULTA
TO LUBRICAR_CONSULTA;


-- Verificar los roles
SELECT ROLE
FROM DBA_ROLES
WHERE ROLE IN (
    'ROL_LUBRICAR_OPERADOR',
    'ROL_LUBRICAR_CONSULTA'
)
ORDER BY ROLE;


SELECT GRANTEE, GRANTED_ROLE
FROM DBA_ROLE_PRIVS
WHERE GRANTEE IN (
    'LUBRICAR_OPERADOR',
    'LUBRICAR_CONSULTA'
)
AND GRANTED_ROLE IN (
    'ROL_LUBRICAR_OPERADOR',
    'ROL_LUBRICAR_CONSULTA'
)
ORDER BY GRANTEE;
