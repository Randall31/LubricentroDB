-- 1 Usuario conectado
SELECT USER AS USUARIO_ACTUAL
FROM DUAL;

-- 2 Cantidad de tablas
SELECT COUNT(*) AS TOTAL_TABLAS
FROM USER_TABLES;

-- 3 Cantidad de registros por tabla
SELECT 'CLIENTE' AS TABLA, COUNT(*) AS TOTAL FROM CLIENTE
UNION ALL
SELECT 'VEHICULO', COUNT(*) FROM VEHICULO
UNION ALL
SELECT 'EMPLEADO', COUNT(*) FROM EMPLEADO
UNION ALL
SELECT 'SERVICIO', COUNT(*) FROM SERVICIO
UNION ALL
SELECT 'PROVEEDOR', COUNT(*) FROM PROVEEDOR
UNION ALL
SELECT 'REPUESTO', COUNT(*) FROM REPUESTO
UNION ALL
SELECT 'ORDEN_SERVICIO', COUNT(*) FROM ORDEN_SERVICIO
UNION ALL
SELECT 'DETALLE_SERVICIO', COUNT(*) FROM DETALLE_SERVICIO
UNION ALL
SELECT 'DETALLE_REPUESTO', COUNT(*) FROM DETALLE_REPUESTO
UNION ALL
SELECT 'FACTURA', COUNT(*) FROM FACTURA
UNION ALL
SELECT 'PAGO', COUNT(*) FROM PAGO
UNION ALL
SELECT 'MOVIMIENTO_INVENTARIO', COUNT(*)
FROM MOVIMIENTO_INVENTARIO;

-- 4 Restricciones de integridad
SELECT CONSTRAINT_TYPE,
       STATUS,
       COUNT(*) AS TOTAL
FROM USER_CONSTRAINTS
WHERE CONSTRAINT_TYPE IN ('P', 'R', 'U')
GROUP BY CONSTRAINT_TYPE, STATUS
ORDER BY CONSTRAINT_TYPE;

-- 5 Permisos concedidos a los roles
SELECT GRANTEE AS ROL,
       PRIVILEGE AS PERMISO,
       COUNT(*) AS TOTAL_TABLAS
FROM USER_TAB_PRIVS_MADE
WHERE GRANTEE IN (
    'ROL_LUBRICAR_OPERADOR',
    'ROL_LUBRICAR_CONSULTA'
)
GROUP BY GRANTEE, PRIVILEGE
ORDER BY GRANTEE, PRIVILEGE;

-- 6 Verificar que no quedó el cliente de prueba
SELECT COUNT(*) AS CLIENTES_DE_PRUEBA
FROM CLIENTE
WHERE ID_CLIENTE = -9999;
